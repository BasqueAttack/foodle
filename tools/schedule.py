"""Build or extend schedule.js, the list of daily Foodle answers.

Usage:  python tools/schedule.py           update schedule.js
        python tools/schedule.py --check   only report problems

Day 0 is Foodle #1 (the launch date below). Past days, today and tomorrow
are never changed, so players' puzzles and streaks stay put. Foods added to
products.js are shuffled into future days, foods removed from products.js are
dropped from future days, and the schedule is kept at least a year ahead.
"""
import datetime as dt, json, random, re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEDULE = ROOT / "schedule.js"
LAUNCH = dt.date(2026, 10, 27)  # keep in sync with LAUNCH in game.js
LOCK_AHEAD = 1                  # also lock tomorrow (time zones ahead of you)
DAYS_AHEAD = 366


def load_products():
    script = "global.window={};require(process.argv[1]);process.stdout.write(JSON.stringify(window.FOODLE_PRODUCTS.map(p=>p.name)))"
    raw = subprocess.run(["node", "-e", script, str(ROOT / "products.js")], capture_output=True, check=True).stdout
    return json.loads(raw.decode("utf-8"))


def load_schedule():
    if not SCHEDULE.exists():
        return []
    return [json.loads(m) for m in re.findall(r'^\s*("(?:[^"\\]|\\.)*"),', SCHEDULE.read_text(encoding="utf-8"), re.M)]


def write_schedule(names):
    lines = [f"  {json.dumps(n, ensure_ascii=False)}, // #{i + 1} {LAUNCH + dt.timedelta(days=i)}" for i, n in enumerate(names)]
    SCHEDULE.write_text(
        "// Daily Foodle answers, one per day starting at Foodle #1. Generated by\n"
        "// tools/schedule.py: edit products.js, then rerun the tool instead of editing here.\n"
        "window.FOODLE_SCHEDULE = [\n" + "\n".join(lines) + "\n];\n",
        encoding="utf-8",
    )


def shuffled(names, avoid_first=None):
    names = list(names)
    random.shuffle(names)
    if avoid_first and len(names) > 1 and names[0] == avoid_first:
        names.append(names.pop(0))  # no same food two days in a row across a cycle boundary
    return names


def main():
    check_only = "--check" in sys.argv
    products = load_products()
    known = set(products)
    schedule = load_schedule()
    today = (dt.date.today() - LAUNCH).days
    lock = max(0, min(len(schedule), today + 1 + LOCK_AHEAD))
    locked, future = schedule[:lock], schedule[lock:]

    problems = [f"#{i + 1} ({LAUNCH + dt.timedelta(days=i)}) uses \"{n}\", which is no longer in products.js"
                for i, n in enumerate(locked) if n not in known]
    gone = [n for n in future if n not in known]
    new = [n for n in products if n not in set(schedule)]
    short = today + DAYS_AHEAD - len(schedule)

    for p in problems:
        print("LOCKED DAY:", p, "(rename it back, or that day falls back to a random food)")
    if check_only:
        print(f"{len(schedule)} days scheduled, through {LAUNCH + dt.timedelta(days=len(schedule) - 1)}" if schedule else "no schedule yet")
        print(f"{len(new)} foods not scheduled yet, {len(gone)} removed foods on future days")
        if short > 0:
            print(f"needs {short} more days to stay a year ahead")
        sys.exit(1 if problems or new or gone or short > 0 else 0)

    future = [n for n in future if n in known] + new
    future = shuffled(future, locked[-1] if locked else None)
    schedule = locked + future
    while len(schedule) < today + DAYS_AHEAD:
        schedule += shuffled(products, schedule[-1] if schedule else None)
    write_schedule(schedule)
    print(f"locked {len(locked)} days, added {len(new)} new foods, dropped {len(gone)} removed foods")
    print(f"schedule.js now covers {len(schedule)} days, through {LAUNCH + dt.timedelta(days=len(schedule) - 1)}")


if __name__ == "__main__":
    main()
